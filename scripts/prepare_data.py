"""Clean the raw dataset, make patient-level splits, cache resized images, and
write reports/data_report.md.

Usage: python scripts/prepare_data.py
"""

import numpy as np
import pandas as pd
from PIL import Image

from embryoscan import paths
from embryoscan.data import load_clinical, load_grades
from embryoscan.report import md_table
from embryoscan.splits import make_grade_split, make_outcome_split

CACHE_HW = (288, 384)  # 0.75x of the original 384x512, keeps the 4:3 shape


def cache_images(files: list[str]) -> None:
    out = paths.PROCESSED / f"images_u8_{CACHE_HW[0]}x{CACHE_HW[1]}.npy"
    if out.exists():
        return
    arr = np.lib.format.open_memmap(out, mode="w+", dtype=np.uint8, shape=(len(files), *CACHE_HW))
    for i, f in enumerate(files):
        with Image.open(paths.IMAGES / f) as im:
            arr[i] = np.asarray(im.convert("L").resize(CACHE_HW[::-1], Image.Resampling.LANCZOS))
    arr.flush()
    pd.Series(files, name="file").to_csv(paths.PROCESSED / "images_index.csv", index=False)


def rate_table(df: pd.DataFrame, by: pd.Series, name: str) -> str:
    g = df.groupby(by, observed=True)["lb"].agg(["count", "sum", "mean"]).reset_index()
    g.columns = [name, "embryos", "live births", "live birth rate"]
    return md_table(g, "{:.2f}")


def main():
    paths.PROCESSED.mkdir(parents=True, exist_ok=True)
    paths.SPLITS.mkdir(parents=True, exist_ok=True)
    paths.REPORTS.mkdir(parents=True, exist_ok=True)

    grades = load_grades()
    clinical = load_clinical()
    grades.to_csv(paths.PROCESSED / "grades.csv", index=False)
    clinical.to_csv(paths.PROCESSED / "clinical.csv", index=False)

    outcome = make_outcome_split(clinical)
    grade_split = make_grade_split(grades, outcome)
    outcome.to_csv(paths.SPLITS / "outcome_split.csv", index=False)
    grade_split.to_csv(paths.SPLITS / "grade_split.csv", index=False)
    cache_images(grades["file"].tolist())

    c = clinical
    r = []
    r.append("# Data report\n\nGenerated by `scripts/prepare_data.py`. Source: Kromp et al. 2023, "
             "*An annotated human blastocyst dataset to benchmark deep learning architectures for in vitro "
             "fertilization*, Scientific Data (CC BY 4.0).\n")
    r.append("## What's in the dataset\n")
    r.append(md_table(pd.DataFrame({
        "item": ["images (512x384 microscope photos, day 4-5 blastocysts)", "patient IDs", "silver-labelled images (one expert)",
                 "gold-labelled images (multi-expert consensus test set)", "images with conflicting silver labels",
                 "unlabelled images", "transferred embryos with clinical data + outcomes", "patients with outcomes"],
        "count": [len(grades), grades.patient.nunique(), (grades.label_set == "silver").sum(),
                  (grades.label_set == "gold").sum(), (grades.label_set == "conflict").sum(),
                  (grades.label_set == "none").sum(), len(c), c.patient.nunique()],
    })))
    r.append("\nThe paper reports 837 patients and 752 transferred embryos; the files contain "
             f"{grades.patient.nunique()} patient IDs and {len(c)} transferred embryos.\n")

    r.append("## Data cleaning\n")
    how = c["amh_how"].value_counts()
    r.append(md_table(pd.DataFrame({
        "problem": ["AMH stored as a date, 'Mon.YY' form (e.g. Jän.26 = 1.26)",
                    "AMH stored as a date, 'DD.Mon' form (e.g. 02.Nov = 2.11)",
                    "...of which ambiguous (01.Apr = 1.4 or 1.04; midpoint used)",
                    "AMH missing", "endometrium stored as a date (08.Mai = 8.5 mm)", "endometrium missing",
                    "egg counts written as sums (10+1)", "egg retrieval count (COC) missing"],
        "rows": [how.get("Mon.YY", 0), how.get("DD.Mon", 0), int(c.amh_ambiguous.sum()), how.get("missing", 0),
                 int((c.endo_how == "DD.Mon").sum()), int(c.endo.isna().sum()), int(c.count_was_sum.sum()),
                 int(c.coc.isna().sum())],
    })))
    r.append("\nImage names are matched on (patient, embryo) numbers because padding is inconsistent "
             "(`187_1.png` in a CSV, `187_01.png` on disk). The undocumented `Fond` column is dropped.\n")

    r.append("## Outcomes (transferred embryos)\n")
    out = pd.DataFrame({
        "outcome": ["positive pregnancy test (SS)", "ongoing pregnancy with heartbeat (HA)", "live birth (LB)"],
        "positive": [c.ss.sum(), c.ha.sum(), c.lb.sum()],
        "negative": [(1 - c.ss).sum(), (1 - c.ha).sum(), (1 - c.lb).sum()],
        "rate": [c.ss.mean(), c.ha.mean(), c.lb.mean()],
    })
    r.append(md_table(out, "{:.3f}"))
    bad = int(((c.lb > c.ha) | (c.ha > c.ss)).sum())
    r.append(f"\nRows where outcomes are out of order (live birth without heartbeat, etc.): {bad}.\n")
    r.append(f"Double embryo transfers: {int((c.n_transferred == 2).sum() / 2)} patients had two embryos "
             "transferred together. Both embryos get the transfer's outcome, so for these we can't tell "
             "which embryo implanted (a known source of label noise in IVF data).\n")
    r.append("**Main target: live birth (LB).** It's the outcome patients care about, and has "
             f"{c.lb.sum()} positives.\n")

    r.append("## Clinical fields\n")
    rows = []
    for col, label in [("age", "female age (years)"), ("amh", "AMH (ng/ml)"), ("endo", "endometrium (mm)"),
                       ("coc", "eggs retrieved (COC)"), ("mii", "mature eggs (MII)")]:
        s = c[col]
        rows.append([label, int(s.notna().sum()), int(s.isna().sum()), s.median(), s.quantile(0.25), s.quantile(0.75),
                     s.min(), s.max()])
    r.append(md_table(pd.DataFrame(rows, columns=["field", "present", "missing", "median", "q1", "q3", "min", "max"]),
                      "{:.2f}"))
    r.append(f"\nTransfer day: day 4 = {(c.day == 4).sum()}, day 5 = {(c.day == 5).sum()}.\n")

    r.append("## Live birth rate by age and by the embryologist's grade\n")
    r.append(rate_table(c, pd.cut(c.age, [0, 29, 34, 37, 40, 99], labels=["<30", "30-34", "35-37", "38-40", ">40"]), "age"))
    r.append("")
    r.append(rate_table(c, c.exp_silver + 1, "expansion grade"))
    r.append("")
    r.append(rate_table(c, c.icm_silver.map({0: "A", 1: "B", 2: "C", 3: "not graded"}), "inner cell mass"))
    r.append("")
    r.append(rate_table(c, c.te_silver.map({0: "A", 1: "B", 2: "C", 3: "not graded"}), "trophectoderm"))

    r.append("\n## Splits (all by patient)\n")
    o = outcome.merge(c[["file", "lb"]], on="file")
    s1 = o.groupby("split").agg(patients=("patient", "nunique"), embryos=("file", "count"), live_births=("lb", "sum")).reset_index()
    r.append("Outcome task (test set is locked until the final evaluation):\n")
    r.append(md_table(s1))
    s2 = grade_split.groupby("split").agg(patients=("patient", "nunique"), images=("file", "count")).reset_index()
    r.append("\nGrading task (the pool is further divided into 5 patient-level folds):\n")
    r.append(md_table(s2))
    leak = int(((grade_split.split == "pool") & grade_split.gold_patient).sum())
    r.append(f"\nThe official gold test set was drawn by image, not by patient: {leak} training images come "
             "from patients who also have a gold test image. Grading results are reported both ways.\n")

    (paths.REPORTS / "data_report.md").write_text("\n".join(r), encoding="utf-8")
    print("\n".join(r))


if __name__ == "__main__":
    main()
