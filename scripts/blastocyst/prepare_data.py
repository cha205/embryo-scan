"""Clean the raw blastocyst dataset, make patient-level splits, cache resized
images, and write reports/blastocyst/data-report.md.

Usage: python scripts/blastocyst/prepare_data.py
"""

import argparse

import numpy as np
import pandas as pd
from PIL import Image

from embryoscan import paths
from embryoscan.blastocyst.data import load_clinical, load_grades
from embryoscan.blastocyst.grading import IMAGE_HW
from embryoscan.blastocyst.splits import make_grade_split, make_outcome_split
from embryoscan.common.reporting import md_table


def cache_images(files: list[str]) -> None:
    """All photos as one uint8 array at 0.75x (288x384, keeps the 4:3 shape)."""
    if paths.BLASTOCYST_IMAGES.exists():
        return
    arr = np.lib.format.open_memmap(paths.BLASTOCYST_IMAGES, mode="w+", dtype=np.uint8, shape=(len(files), *IMAGE_HW))
    for i, f in enumerate(files):
        with Image.open(paths.KROMP_IMAGES / f) as im:
            arr[i] = np.asarray(im.convert("L").resize(IMAGE_HW[::-1], Image.Resampling.LANCZOS))
    arr.flush()
    pd.Series(files, name="file").to_csv(paths.BLASTOCYST_IMAGE_INDEX, index=False)


def rate_table(df: pd.DataFrame, by: pd.Series, name: str) -> str:
    g = df.groupby(by, observed=True)["lb"].agg(["count", "sum", "mean"]).reset_index()
    g.columns = [name, "embryos", "live births", "live birth rate"]
    return md_table(g, "{:.2f}")


def main():
    argparse.ArgumentParser(description=__doc__.split("\n\n")[0]).parse_args()
    paths.BLASTOCYST_CACHE.mkdir(parents=True, exist_ok=True)
    paths.SPLITS.mkdir(parents=True, exist_ok=True)

    grades = load_grades()
    clinical = load_clinical()
    grades.to_csv(paths.BLASTOCYST_GRADES, index=False)
    clinical.to_csv(paths.BLASTOCYST_CLINICAL, index=False)

    outcome = make_outcome_split(clinical)
    grade_split = make_grade_split(grades, outcome)
    outcome.to_csv(paths.SPLIT_OUTCOME, index=False)
    grade_split.to_csv(paths.SPLIT_GRADING, index=False)
    cache_images(grades["file"].tolist())

    c = clinical
    r = []
    r.append(
        "# Data report\n\nThis report is generated by `scripts/blastocyst/prepare_data.py`. The source is "
        "Kromp et al. (2023), *An annotated human blastocyst dataset to benchmark deep learning architectures for "
        "in vitro fertilization*, Scientific Data (CC BY 4.0).\n"
    )
    r.append("## Dataset contents\n")
    r.append(
        md_table(
            pd.DataFrame(
                {
                    "item": [
                        "images (512 x 384 microscope images of day-4 and day-5 blastocysts)",
                        "patient identifiers",
                        "silver-labelled images (single embryologist)",
                        "gold-labelled images (consensus test set of an expert panel)",
                        "images with conflicting silver labels",
                        "unlabelled images",
                        "transferred embryos with clinical data and outcomes",
                        "patients with outcomes",
                    ],
                    "count": [
                        len(grades),
                        grades.patient.nunique(),
                        (grades.label_set == "silver").sum(),
                        (grades.label_set == "gold").sum(),
                        (grades.label_set == "conflict").sum(),
                        (grades.label_set == "none").sum(),
                        len(c),
                        c.patient.nunique(),
                    ],
                }
            )
        )
    )
    r.append(
        "\nThe original publication reports 837 patients and 752 transferred embryos, whereas the released files "
        f"contain {grades.patient.nunique()} patient identifiers and {len(c)} transferred embryos.\n"
    )

    r.append("## Data cleaning\n")
    how = c["amh_how"].value_counts()
    r.append(
        md_table(
            pd.DataFrame(
                {
                    "defect": [
                        "AMH stored as a date, 'Mon.YY' form (e.g. Jän.26 = 1.26)",
                        "AMH stored as a date, 'DD.Mon' form (e.g. 02.Nov = 2.11)",
                        "...of which ambiguous (01.Apr = 1.4 or 1.04; midpoint used)",
                        "AMH missing",
                        "endometrial thickness stored as a date (08.Mai = 8.5 mm)",
                        "endometrial thickness missing",
                        "oocyte counts written as sums (10+1)",
                        "number of cumulus-oocyte complexes (COC) missing",
                    ],
                    "rows": [
                        how.get("Mon.YY", 0),
                        how.get("DD.Mon", 0),
                        int(c.amh_ambiguous.sum()),
                        how.get("missing", 0),
                        int((c.endo_how == "DD.Mon").sum()),
                        int(c.endo.isna().sum()),
                        int(c.count_was_sum.sum()),
                        int(c.coc.isna().sum()),
                    ],
                }
            )
        )
    )
    r.append(
        "\nImage names are matched on (patient, embryo) numbers because their zero-padding is inconsistent "
        "(`187_1.png` in a CSV file and `187_01.png` on disk). The undocumented `Fond` column is discarded.\n"
    )

    r.append("## Outcomes (transferred embryos)\n")
    out = pd.DataFrame(
        {
            "outcome": [
                "positive pregnancy test (SS)",
                "ongoing pregnancy with fetal heartbeat (HA)",
                "live birth (LB)",
            ],
            "positive": [c.ss.sum(), c.ha.sum(), c.lb.sum()],
            "negative": [(1 - c.ss).sum(), (1 - c.ha).sum(), (1 - c.lb).sum()],
            "rate": [c.ss.mean(), c.ha.mean(), c.lb.mean()],
        }
    )
    r.append(md_table(out, "{:.3f}"))
    bad = int(((c.lb > c.ha) | (c.ha > c.ss)).sum())
    r.append(f"\nNumber of rows with inconsistent outcomes (for example, a live birth without a heartbeat): {bad}.\n")
    r.append(
        f"In {int((c.n_transferred == 2).sum() / 2)} patients, two embryos were transferred together. Both "
        "embryos inherit the outcome of the transfer, so it cannot be determined which embryo implanted; this is a "
        "known source of label noise in IVF data.\n"
    )
    r.append(
        "**Primary outcome: live birth (LB).** Live birth is the outcome of greatest clinical relevance, and "
        f"{c.lb.sum()} transferred embryos resulted in a live birth.\n"
    )

    r.append("## Clinical variables\n")
    rows = []
    for col, label in [
        ("age", "maternal age (years)"),
        ("amh", "AMH (ng/ml)"),
        ("endo", "endometrial thickness (mm)"),
        ("coc", "cumulus-oocyte complexes (COC)"),
        ("mii", "metaphase II oocytes (MII)"),
    ]:
        s = c[col]
        rows.append(
            [
                label,
                int(s.notna().sum()),
                int(s.isna().sum()),
                s.median(),
                s.quantile(0.25),
                s.quantile(0.75),
                s.min(),
                s.max(),
            ]
        )
    r.append(
        md_table(
            pd.DataFrame(rows, columns=["variable", "present", "missing", "median", "q1", "q3", "min", "max"]), "{:.2f}"
        )
    )
    r.append(f"\nEmbryos were transferred on day 4 ({(c.day == 4).sum()}) or day 5 ({(c.day == 5).sum()}).\n")

    r.append("## Live-birth rate by maternal age and by the embryologist's grade\n")
    r.append(
        rate_table(c, pd.cut(c.age, [0, 29, 34, 37, 40, 99], labels=["<30", "30-34", "35-37", "38-40", ">40"]), "age")
    )
    r.append("")
    r.append(rate_table(c, c.exp_silver + 1, "expansion grade"))
    r.append("")
    r.append(rate_table(c, c.icm_silver.map({0: "A", 1: "B", 2: "C", 3: "not graded"}), "inner cell mass"))
    r.append("")
    r.append(rate_table(c, c.te_silver.map({0: "A", 1: "B", 2: "C", 3: "not graded"}), "trophectoderm"))

    r.append("\n## Partitions (all at the patient level)\n")
    o = outcome.merge(c[["file", "lb"]], on="file")
    s1 = (
        o.groupby("split")
        .agg(patients=("patient", "nunique"), embryos=("file", "count"), live_births=("lb", "sum"))
        .reset_index()
        .rename(columns={"live_births": "live births"})
    )
    r.append("Outcome task (the test set is reserved for a final confirmatory evaluation):\n")
    r.append(md_table(s1))
    s2 = grade_split.groupby("split").agg(patients=("patient", "nunique"), images=("file", "count")).reset_index()
    r.append("\nGrading task (the training pool is further divided into five patient-level folds):\n")
    r.append(md_table(s2))
    leak = int(((grade_split.split == "pool") & grade_split.gold_patient).sum())
    r.append(
        f"\nThe official gold test set was drawn by image rather than by patient, so {leak} training images come "
        "from patients who also contribute a gold test image. Grading results are therefore also reported for "
        "models trained without these patients ([patient-overlap-check.md](patient-overlap-check.md)).\n"
    )

    paths.report("blastocyst", "data-report.md").write_text("\n".join(r), encoding="utf-8")
    print("\n".join(r))


if __name__ == "__main__":
    main()
